CREATE TABLE IF NOT EXISTS classification_groups (
  code VARCHAR(10) PRIMARY KEY,
  name TEXT NOT NULL,
  archive_type ENUM('SUBSTANTIF','FASILITATIF') NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_group_archive (archive_type,is_active,sort_order)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS classification_items (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  group_code VARCHAR(10) NOT NULL,
  raw_code VARCHAR(10) NOT NULL,
  code VARCHAR(10) NOT NULL,
  name TEXT NOT NULL,
  description TEXT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_classification_item (group_code,code),
  INDEX idx_classification_lookup (group_code,is_active,sort_order),
  CONSTRAINT fk_classification_group FOREIGN KEY(group_code) REFERENCES classification_groups(code)
) ENGINE=InnoDB;

